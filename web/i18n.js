let lang = 'fr';
export const setUiLang = l => { lang = UI_LANGS.includes(l) ? l : 'fr'; document.documentElement.lang = lang; };
export const uiLang = () => lang;

/** Texte traduit ; une entrée fonction reçoit les arguments. Repli sur le français. */
export function t(key, ...args) {
  const v = T[lang][key] ?? T.fr[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}
export const posLabel = (code, serverLabel) => T[lang].pos[code] ?? serverLabel ?? code;

/** Applique les textes statiques : data-i18n (texte), data-i18n-ph (placeholder), data-i18n-title (title),
 *  data-i18n-label (aria-label, pour les boutons à icône). */
export function applyStaticTexts(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-label]')) el.setAttribute('aria-label', t(el.dataset.i18nLabel));
}
